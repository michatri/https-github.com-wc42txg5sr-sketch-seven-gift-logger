def account_kind(code: int | str) -> str:
    try:
        n = int(str(code).split()[0])
    except (TypeError, ValueError):
        return "unknown"
    if 4100 <= n < 5000:
        return "income"
    if 5100 <= n < 6000:
        return "expense"
    return "unknown"


